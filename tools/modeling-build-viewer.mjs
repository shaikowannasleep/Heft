// Rebuilds src/modeling/viewer.generated.js: three.js and OrbitControls as one IIFE string, inlined by preview.html.
// Run after changing the three.js version: node tools/modeling-build-viewer.mjs
import { build } from 'vite';
import fs from 'node:fs';

const root = new URL('../', import.meta.url);
const out = await build({
  configFile: false, logLevel: 'warn', root: root.pathname,
  build: { write: false, minify: true, emptyOutDir: false,
    lib: { entry: new URL('../src/modeling/viewer-lib.js', import.meta.url).pathname, name: 'HeftLib', formats: ['iife'], fileName: 'heft-lib' } },
});
const chunk = [].concat(out).flatMap(o => o.output).find(c => c.type === 'chunk');
if (!chunk) throw new Error('viewer build produced no chunk');
fs.writeFileSync(new URL('../src/modeling/viewer.generated.js', import.meta.url),
  `// Generated by tools/modeling-build-viewer.mjs. Do not edit.\nexport const LIB = ${JSON.stringify(chunk.code)};\n`);
console.log(`viewer.generated.js: ${chunk.code.length} bytes`);
