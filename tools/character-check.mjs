import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const browser = await chromium.launch({headless:true});
const page = await browser.newPage({viewport:{width:1440,height:1000}});
await page.route('https://cdn.jsdelivr.net/npm/three@0.186.1/build/*', route => route.fulfill({path: new URL('../node_modules/three/build/' + new URL(route.request().url()).pathname.split('/').pop().replace('.min.js','.js'), import.meta.url).pathname, contentType:'application/javascript'}));
const errors=[]; page.on('pageerror',e=>(errors.push(e.message),console.error(e.message)));
await page.goto('http://localhost:8123');
await page.waitForFunction(()=>!!window.heft);
await page.locator('[data-character="fern"]').click();
assert.equal(await page.locator('#characterName').textContent(),'Fern');
await page.screenshot({path:'/Users/macbook/Heft/character-selection.png'});
await page.locator('#btnNew').click();
assert.equal(await page.evaluate(()=>heft.serialize().player.character),'fern');
await page.reload(); await page.waitForFunction(()=>!!window.heft);
assert.equal(await page.locator('#characterName').textContent(),'Fern');
await page.locator('[data-character="orin"]').click();
await page.locator('#btnContinue').click();
assert.equal(await page.evaluate(()=>heft.serialize().player.character),'fern');
await page.reload(); await page.waitForFunction(()=>!!window.heft);
await page.setViewportSize({width:390,height:844});
assert.equal(await page.evaluate(()=>document.querySelector('.selection').scrollWidth <= innerWidth),true);
await page.locator('[data-character="orin"]').click();
await page.locator('#btnNew').click();
assert.equal(await page.evaluate(()=>heft.serialize().player.character),'orin');
await page.evaluate(()=>{const s=heft.newState(); delete s.player.character; heft.applyState(s)});
assert.equal(await page.evaluate(()=>heft.serialize().player.character),'bram');
assert.deepEqual(errors,[]);
await browser.close(); console.log('PASS: selection, new game, save restoration, continue, mobile width, legacy saves, no runtime errors');
